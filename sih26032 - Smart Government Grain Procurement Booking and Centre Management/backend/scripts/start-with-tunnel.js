// Single entrypoint (`npm start`): brings up Postgres+Redis via Docker, starts
// the Express API, opens a public ngrok tunnel to it, and writes that public
// URL into the Flutter app's api_config.dart so the app talks to the backend
// even when the phone is off USB / off the same network as this machine.
//
// Spawns the `ngrok` CLI directly (rather than the `ngrok` npm wrapper package,
// whose v5 beta `connect()` has a flaky retry-on-timeout bug that double-POSTs
// the tunnel-create request and then fails on the resulting "already exists")
// and reads the public URL back from ngrok's local inspector API.
require('dotenv').config();
const { execSync, spawn } = require('child_process');
const os = require('os');
const path = require('path');
const fs = require('fs');
const http = require('http');

const BACKEND_DIR = path.join(__dirname, '..');
const API_CONFIG_PATH = path.join(
  BACKEND_DIR,
  '..',
  'agriva',
  'lib',
  'core',
  'config',
  'api_config.dart',
);
const NGROK_LOCAL_API = 'http://127.0.0.1:4040/api/tunnels';

function lanIp() {
  const ifaces = os.networkInterfaces();
  for (const name of Object.keys(ifaces)) {
    for (const iface of ifaces[name] ?? []) {
      if (iface.family === 'IPv4' && !iface.internal) return iface.address;
    }
  }
  return 'localhost';
}

function writeApiConfig(baseUrl) {
  fs.mkdirSync(path.dirname(API_CONFIG_PATH), { recursive: true });
  const contents = `// AUTO-GENERATED by backend/scripts/start-with-tunnel.js — do not edit by hand.
// Overwritten every time \`npm start\` runs in backend/. Rebuild/reinstall the
// app (\`flutter run\`) after this changes, since it's a compiled-in const.
const String kApiBaseUrl = '${baseUrl}';
`;
  fs.writeFileSync(API_CONFIG_PATH, contents);
  console.log(`\nWrote ${baseUrl} to agriva/lib/core/config/api_config.dart`);
}

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    http
      .get(url, (res) => {
        let data = '';
        res.on('data', (chunk) => (data += chunk));
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (err) {
            reject(err);
          }
        });
      })
      .on('error', reject);
  });
}

async function waitForNgrokUrl({ retries = 30, delayMs = 500 } = {}) {
  for (let attempt = 1; attempt <= retries; attempt++) {
    try {
      const { tunnels } = await fetchJson(NGROK_LOCAL_API);
      const httpsTunnel = (tunnels ?? []).find((t) => t.proto === 'https');
      if (httpsTunnel) return httpsTunnel.public_url;
    } catch (_) {
      // ngrok's local API isn't up yet — keep retrying.
    }
    await new Promise((resolve) => setTimeout(resolve, delayMs));
  }
  throw new Error('Timed out waiting for ngrok to report a public URL');
}

/** Spawns `ngrok http <port>`, waits for the tunnel to come up, returns {url, child}. */
async function startNgrokTunnel(port, authtoken) {
  const child = spawn('ngrok', ['http', String(port), '--log=stdout'], {
    env: { ...process.env, NGROK_AUTHTOKEN: authtoken },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  child.stdout.on('data', () => {}); // drain, avoid backpressure blocking the process
  child.stderr.on('data', () => {});

  const exitedEarly = new Promise((_, reject) => {
    child.once('exit', (code) => reject(new Error(`ngrok exited early (code ${code})`)));
  });

  const url = await Promise.race([waitForNgrokUrl(), exitedEarly]);
  return { url, child };
}

async function main() {
  console.log('Starting Postgres + Redis (docker compose up -d)...');
  execSync('docker compose up -d', { cwd: BACKEND_DIR, stdio: 'inherit' });

  const { startServer } = require('../server');
  const PORT = Number(process.env.PORT) || 8080;
  await startServer();

  const authtoken = process.env.NGROK_AUTHTOKEN;
  let baseUrl;
  let ngrokChild;

  if (authtoken) {
    console.log('Opening ngrok tunnel...');
    try {
      const { url, child } = await startNgrokTunnel(PORT, authtoken);
      ngrokChild = child;
      baseUrl = `${url}/api/v1`;
      console.log(`Public URL: ${url}`);
    } catch (err) {
      console.warn(`\nngrok tunnel failed (${err.message}) — falling back to LAN IP.`);
    }
  } else {
    console.warn('\nNGROK_AUTHTOKEN not set in backend/.env — falling back to LAN IP.');
  }

  if (!baseUrl) {
    const ip = lanIp();
    baseUrl = `http://${ip}:${PORT}/api/v1`;
    console.warn(
      `Using ${baseUrl} — this only works if the phone is on the same Wi-Fi as this ` +
        'machine. Sign up free at ngrok.com, copy your authtoken, and set ' +
        'NGROK_AUTHTOKEN in backend/.env to get a public URL that works anywhere.',
    );
  }

  writeApiConfig(baseUrl);
  console.log('\nBackend ready. Run `flutter run` in agriva/ to pick up the new URL.');

  const shutdown = () => {
    console.log('\nShutting down...');
    ngrokChild?.kill();
    process.exit(0);
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

main().catch((err) => {
  console.error('Failed to start:', err);
  process.exit(1);
});
